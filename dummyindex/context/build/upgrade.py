"""Context-layout migration: managed scratch rules and retired-path cleanup.

:func:`migrate_context_layout` brings an older ``.context/`` forward; each step runs in
its own ``try`` so one failure never blocks the others or the calling build. Retired
paths are removed wholesale: proven-generated files are deleted, other regular files are
first backed up under ``_doc_backups/retired/<retired_in>/``. This module never imports
``runner`` (which re-exports from here) or ``installer`` (a higher layer).
"""

from __future__ import annotations

import itertools
import json
import os
import stat
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import TypeVar

from dummyindex.context.domains.atomic_io import _replace_bytes, is_link
from dummyindex.pipeline.io.cache import scope_cache_to_version

_T = TypeVar("_T")

# Single source for the managed .context/.gitignore (fresh body and upgrade merge).
# Bare filenames match at any depth, which is how per-feature scratch such as
# features/<id>/council/_council-log.json gets ignored.
_MANAGED_GITIGNORE_PATTERNS: tuple[str, ...] = (
    "cache/",
    "_doc_backups/",
    # Session scratch/log artefacts, never committed docs. `_enrich_plan.json` now
    # lives under cache/; the bare name also hides a legacy root-level copy.
    "_enrich_plan.json",
    "_structural-plan.json",
    "_council-log.json",
    "_reality-check.json",
    "_reality-check.md",
)

_CONTEXT_GITIGNORE_HEADER = (
    "# Generated by dummyindex. These are local scratch/cache artefacts that\n"
    "# regenerate automatically — don't commit them.\n"
)

# Marked `linguist-generated` so GitHub folds their rebuild churn out of PR review. They
# stay committed: a fresh clone must navigate .context/ without the CLI, and reconcile
# diffs the committed index. Deliberately no `-diff`: it would also suppress local
# `git diff` and hide merge conflicts.
_MANAGED_GITATTRIBUTES_RULES: tuple[str, ...] = (
    "tree.json linguist-generated",
    "map/files.json linguist-generated",
    "map/symbols.json linguist-generated",
    "features/symbol-graph.json linguist-generated -text",
    "features/symbol-graph.parts/*.json linguist-generated -text",
    "coverage.json linguist-generated",
    "features/graph.json linguist-generated",
    "features/graph.html linguist-generated",
)

_CONTEXT_GITATTRIBUTES_HEADER = (
    "# Generated by dummyindex. The machine-layer artefacts below are\n"
    "# committed by design but their diffs are rebuild noise —\n"
    "# `linguist-generated` collapses them in GitHub PR review.\n"
)


def _context_gitignore_body() -> str:
    """Render the full managed body: header comment + one pattern per line."""
    return _CONTEXT_GITIGNORE_HEADER + "".join(
        f"{pattern}\n" for pattern in _MANAGED_GITIGNORE_PATTERNS
    )


def _ensure_managed_lines(
    path: Path, header: str, managed_lines: tuple[str, ...]
) -> None:
    """Write/upgrade a managed line-oriented file (gitignore/gitattributes).

    Fresh file: write header + every managed line. Existing file: append only
    the managed lines that are missing (stripped line comparison), preserving
    user-added lines and any header — pure-merge, never drops a user line.
    Idempotent: a second call with nothing missing rewrites nothing.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists():
        path.write_text(
            header + "".join(f"{line}\n" for line in managed_lines),
            encoding="utf-8",
        )
        return

    current = path.read_text(encoding="utf-8")
    present = {line.strip() for line in current.splitlines() if line.strip()}
    missing = [line for line in managed_lines if line not in present]
    if not missing:
        return
    addition = "".join(f"{line}\n" for line in missing)
    path.write_text(current.rstrip() + "\n" + addition, encoding="utf-8")


def ensure_context_gitignore(context_dir: Path) -> None:
    """Write/upgrade the managed .gitignore inside .context/.

    Public on purpose: the non-build verbs that create scratch artefacts
    (e.g. ``enrich-plan``) call this too, so a repo maintained purely via
    the reconcile path still receives new managed patterns. Merge semantics
    are documented on :func:`_ensure_managed_lines`.
    """
    _ensure_managed_lines(
        context_dir / ".gitignore",
        _CONTEXT_GITIGNORE_HEADER,
        _MANAGED_GITIGNORE_PATTERNS,
    )


def ensure_context_gitattributes(context_dir: Path) -> None:
    """Write/upgrade the managed .gitattributes inside .context/.

    Marks the heavy machine-layer artefacts ``linguist-generated`` (see
    ``_MANAGED_GITATTRIBUTES_RULES`` for the commit-policy rationale) while
    the curated taxonomy stays reviewable. Same pure-merge semantics as the
    managed .gitignore.
    """
    _ensure_managed_lines(
        context_dir / ".gitattributes",
        _CONTEXT_GITATTRIBUTES_HEADER,
        _MANAGED_GITATTRIBUTES_RULES,
    )


def remove_legacy_enrich_plan(context_dir: Path) -> bool:
    """Unlink the pre-0.21 root-level ``.context/_enrich_plan.json``.

    Versions <= 0.20 wrote it at the root; it now lives under ``cache/``. The bare-name
    gitignore pattern only hides the stale copy, so this removes the file. The current
    ``cache/_enrich_plan.json`` is never touched. ``True`` when a stale copy was removed.
    """
    legacy = context_dir / "_enrich_plan.json"
    if not legacy.is_file():
        return False
    legacy.unlink()
    return True


# --- Vendored v0.36 starter-suite renderer: retire-only, never write with it
# Byte-exact re-render of the suites v0.36.0 `equip apply` seeded (cli/equip/seed.py,
# domains/equip/eval/ @ 38c360258b125d575807596efdcc4df333fc1f20). Capabilities are
# frozen here, not imported, so a later enum change can never alter what counts as generated.
_SUITE_SUFFIX = ".suite.json"
_POSITIVE_SUFFIX = "-positive"
_ENUM_PREFIX = "Capability."
_V036_CAPABILITIES: dict[str, str] = {
    "IMPLEMENT": "implement",
    "TEST": "test",
    "VERIFY": "verify",
    "REVIEW": "review",
    "FORMAT": "format",
    "DATABASE": "database",
    "DATA": "data",
    "SECURITY": "security",
    "FRONTEND": "frontend",
    "PERFORMANCE": "performance",
    "DOCS": "docs",
    "SEARCH": "search",
}
_V036_CAPABILITY_NAMES: dict[str, str] = {
    value: name for name, value in _V036_CAPABILITIES.items()
}


def _v036_suite_text(tool: str, caps: tuple[tuple[str, str], ...]) -> str:
    """Render ``<tool>.suite.json`` exactly as v0.36 ``seed_starter_suites`` did.

    ``caps`` holds ``(f"{cap}", f"{cap!r}")`` pairs — the two interpolations
    ``starter_suite_cases`` made of each capability (case id, prompt).
    """
    cases: list[dict[str, object]] = [
        {
            "case_id": f"{case_token}-positive",
            "prompt": (
                f"<replace: a synthetic prompt that SHOULD trigger the {tool} "
                f"tool for its {repr_token} capability>"
            ),
            "expects_trigger": True,
        }
        for case_token, repr_token in caps[:2]
    ]
    if not cases:
        cases.append(
            {
                "case_id": "positive",
                "prompt": (
                    f"<replace: a synthetic prompt that SHOULD trigger the {tool} tool>"
                ),
                "expects_trigger": True,
            }
        )
    cases.append(
        {
            "case_id": "decoy-negative",
            "prompt": "<replace: an unrelated prompt that should NOT trigger this tool>",
            "expects_trigger": False,
        }
    )
    return json.dumps({"cases": cases}, indent=2) + "\n"


def _cap_renderings(token: str) -> tuple[tuple[str, str], ...]:
    """Every ``(f"{cap}", f"{cap!r}")`` pair v0.36 could have written as ``token``.

    - plain ``str`` capability: ``test`` / ``'test'``;
    - ``Capability`` member on py3.11+: ``Capability.TEST`` /
      ``<Capability.TEST: 'test'>``;
    - ``Capability`` member on py3.10, whose mix-in ``__format__`` yields the
      value: ``test`` / ``<Capability.TEST: 'test'>``.
    """
    if token.startswith(_ENUM_PREFIX):
        name = token[len(_ENUM_PREFIX) :]
        value = _V036_CAPABILITIES.get(name)
        if value is None:
            return ()
        return ((token, f"<Capability.{name}: {value!r}>"),)
    renderings = [(token, repr(token))]
    member = _V036_CAPABILITY_NAMES.get(token)
    if member is not None:
        renderings.append((token, f"<Capability.{member}: {token!r}>"))
    return tuple(renderings)


def _positive_cap_tokens(payload: object) -> tuple[str, ...] | None:
    """The ``{cap}`` part of every ``<cap>-positive`` case id, in suite order.

    ``None`` when ``payload`` is not suite-shaped or names more capabilities
    than v0.36 ever seeded (two).
    """
    cases = payload.get("cases") if isinstance(payload, dict) else None
    if not isinstance(cases, list):
        return None
    tokens = tuple(
        case["case_id"][: -len(_POSITIVE_SUFFIX)]
        for case in cases
        if isinstance(case, dict)
        and isinstance(case.get("case_id"), str)
        and case["case_id"].endswith(_POSITIVE_SUFFIX)
    )
    return tokens if len(tokens) <= 2 else None


def _is_starter_suite(path: Path) -> bool:
    """``True`` only for a byte-exact v0.36 starter suite (``\\r\\n`` → ``\\n``).

    The tool name is the filename minus ``.suite.json``; the capabilities come
    from the file's own ``<cap>-positive`` case ids. Every rendering those
    tokens could have come from is re-rendered and compared, so any edit — a
    changed prompt, an extra case or key, a flipped label, a BOM — fails the
    match. Unreadable, undecodable or non-JSON input is ``False``; never raises.
    """
    name = path.name
    if not name.endswith(_SUITE_SUFFIX) or name == _SUITE_SUFFIX:
        return False
    tool = name[: -len(_SUITE_SUFFIX)]
    try:
        data = path.read_bytes().replace(b"\r\n", b"\n")
        payload = json.loads(data.decode("utf-8"))
    except (OSError, ValueError, RecursionError):
        return False
    tokens = _positive_cap_tokens(payload)
    if tokens is None:
        return False
    options = [_cap_renderings(token) for token in tokens]
    return any(
        _v036_suite_text(tool, caps).encode("utf-8") == data
        for caps in itertools.product(*options)
    )


def _never_generated(path: Path) -> bool:
    """No file under the path is provably ours: back every one of them up."""
    return False


# --- Retired paths


@dataclass(frozen=True)
class RetiredPath:
    """A ``.context/``-relative path that no current dummyindex reads or writes.

    ``retired_in`` is the version that dropped it (it names the backup
    folder); ``is_generated`` proves a regular file under it is unedited
    generator output, safe to delete without a backup.
    """

    rel_path: str
    retired_in: str
    is_generated: Callable[[Path], bool]


RETIRED_CONTEXT_PATHS: tuple[RetiredPath, ...] = (
    # Starter eval suites seeded by `equip apply`; the eval stage left in 0.37.
    RetiredPath("equipment-evals", "0.37.0", _is_starter_suite),
    # Pre-v0.6 graph layout. The build paths rewrite the symbol graph right
    # after, so it is backed up and removed, not promoted (refresh-indexes
    # keeps its promotion in cli/migrate.py).
    RetiredPath("graph", "0.6.0", _never_generated),
)

_BACKUP_ROOT: tuple[str, ...] = ("_doc_backups", "retired")
_MAX_BACKUP_SUFFIX = 100


class _Retirer:
    """Walks retired paths under one ``.context/``, collecting outcomes.

    Links are never followed: every entry is ``lstat``-ed, a link (or
    junction) is unlinked as an entry, and only real directories are
    descended. Every per-entry failure is recorded and the walk moves on.
    """

    def __init__(self, context_dir: Path) -> None:
        self.context_dir = context_dir
        self.removed: list[str] = []
        self.backed_up: list[str] = []
        self.errors: list[str] = []
        try:
            self._context_real: Path | None = context_dir.resolve()
        except (OSError, RuntimeError):
            self._context_real = None

    def retire(self, entry: RetiredPath) -> None:
        self._retire_entry(self.context_dir / entry.rel_path, entry)

    def _rel(self, path: Path) -> str:
        return path.relative_to(self.context_dir).as_posix()

    def _fail(self, path: Path, error: object) -> bool:
        self.errors.append(f"{self._rel(path)}: {error}")
        return False

    def _inside(self, path: Path) -> bool:
        """Whether ``path`` really resolves under ``.context/``."""
        if self._context_real is None:
            return False
        try:
            return path.resolve().is_relative_to(self._context_real)
        except (OSError, RuntimeError):
            return False

    def _retire_entry(self, path: Path, entry: RetiredPath) -> bool:
        """Retire one entry; ``True`` when nothing is left behind."""
        try:
            info = os.lstat(path)
        except FileNotFoundError:
            return True
        except OSError as exc:
            return self._fail(path, exc)
        if is_link(path):
            return self._remove_link(path)
        if stat.S_ISDIR(info.st_mode):
            return self._retire_dir(path, entry)
        if stat.S_ISREG(info.st_mode):
            return self._retire_file(path, entry)
        return self._unlink(path)  # fifo / socket / device: no bytes to keep

    def _remove_link(self, path: Path) -> bool:
        """Remove a symlink or junction itself; its target is never touched."""
        try:
            os.unlink(path)
        except OSError as exc:
            try:
                os.rmdir(path)  # a directory reparse point Windows won't unlink
            except OSError:
                return self._fail(path, exc)
        self.removed.append(self._rel(path))
        return True

    def _retire_dir(self, directory: Path, entry: RetiredPath) -> bool:
        if not self._inside(directory):
            return self._fail(directory, "resolves outside .context/; left in place")
        try:
            with os.scandir(directory) as listing:
                children = sorted(Path(child.path) for child in listing)
        except OSError as exc:
            return self._fail(directory, exc)
        clean = True
        for child in children:
            clean = self._retire_entry(child, entry) and clean
        if not clean:
            return False  # the leftover's own failure is already recorded
        try:
            os.rmdir(directory)
        except FileNotFoundError:
            pass
        except OSError as exc:
            return self._fail(directory, exc)
        return True

    def _retire_file(self, path: Path, entry: RetiredPath) -> bool:
        if not self._inside(path):
            return self._fail(path, "resolves outside .context/; left in place")
        try:
            generated = entry.is_generated(path)
        except Exception:  # noqa: BLE001 — unproven means backed up, never lost
            generated = False
        if not generated:
            try:
                self.backed_up.append(self._back_up(path, entry.retired_in))
            except OSError as exc:
                return self._fail(path, f"backup failed, left in place: {exc}")
        return self._unlink(path)

    def _back_up(self, path: Path, retired_in: str) -> str:
        """Copy ``path`` byte-for-byte under ``_doc_backups/retired/<ver>/``.

        An existing identical backup is reused; a different one is never
        overwritten — the copy takes the next free ``<stem>.<n><suffix>``
        name. Returns the backup's ``.context/``-relative POSIX path.
        """
        data = path.read_bytes()
        base = self.context_dir.joinpath(
            *_BACKUP_ROOT, retired_in, *Path(self._rel(path)).parts
        )
        self._refuse_linked_parents(base)
        for n in range(_MAX_BACKUP_SUFFIX):
            dest = base if n == 0 else base.with_name(f"{base.stem}.{n}{base.suffix}")
            try:
                info = os.lstat(dest)
            except FileNotFoundError:
                info = None
            if info is None:
                dest.parent.mkdir(parents=True, exist_ok=True)
                if not self._inside(dest.parent):
                    raise OSError(f"{self._rel(dest)} resolves outside .context/")
                _replace_bytes(dest, data)
                return self._rel(dest)
            if is_link(dest):
                raise OSError(f"{self._rel(dest)} is a link; refusing to follow it")
            if stat.S_ISREG(info.st_mode) and dest.read_bytes() == data:
                return self._rel(dest)
        raise OSError(f"no free backup name for {self._rel(base)}")

    def _refuse_linked_parents(self, dest: Path) -> None:
        """Raise before ``mkdir`` could follow a linked backup ancestor."""
        current = self.context_dir
        for part in dest.relative_to(self.context_dir).parts[:-1]:
            current = current / part
            if is_link(current):
                raise OSError(f"{self._rel(current)} is a link; refusing to follow it")

    def _unlink(self, path: Path) -> bool:
        try:
            os.unlink(path)
        except FileNotFoundError:
            return True
        except OSError as exc:
            return self._fail(path, exc)
        self.removed.append(self._rel(path))
        return True


def retire_paths(
    context_dir: Path,
    retired: tuple[RetiredPath, ...] = RETIRED_CONTEXT_PATHS,
) -> tuple[tuple[str, ...], tuple[str, ...], tuple[str, ...]]:
    """Remove every registered retired path under ``context_dir`` wholesale.

    A regular file is deleted when ``is_generated`` proves it ours, else first copied to
    ``_doc_backups/retired/<retired_in>/<rel>`` (gitignored). Links/junctions are unlinked,
    never followed; nothing resolving outside ``.context/`` is opened. Idempotent. Returns
    ``(removed, backed_up, errors)``: ``.context/``-relative POSIX paths, then
    ``"<rel>: <error>"`` per entry left in place. Never raises for a per-entry failure.
    """
    retirer = _Retirer(Path(context_dir))
    for entry in retired:
        retirer.retire(entry)
    return tuple(retirer.removed), tuple(retirer.backed_up), tuple(retirer.errors)


# --- One migration entry point


@dataclass(frozen=True)
class LayoutMigration:
    """What :func:`migrate_context_layout` changed (``.context/``-relative)."""

    removed: tuple[str, ...] = ()
    backed_up: tuple[str, ...] = ()
    errors: tuple[str, ...] = ()


def _attempt(step: str, action: Callable[[], _T], errors: list[str]) -> _T | None:
    """Run one migration step, recording any failure instead of raising."""
    try:
        return action()
    except Exception as exc:  # noqa: BLE001 — one step must never block the rest
        errors.append(f"{step}: {exc}")
        return None


def migrate_context_layout(
    context_dir: Path, *, package_version: str | None
) -> LayoutMigration:
    """Bring ``context_dir`` forward to the current layout; never raises.

    Steps, each contained: managed ``.gitignore`` and ``.gitattributes``, the
    legacy root ``_enrich_plan.json``, :func:`retire_paths`, and — when
    ``package_version`` is a non-empty string — the extraction-cache version
    scope (stale entries reported as ``"cache: N stale extraction entries"``).
    Idempotent: a second run returns empty ``removed`` and ``backed_up``.
    """
    context_dir = Path(context_dir)
    removed: list[str] = []
    backed_up: list[str] = []
    errors: list[str] = []

    _attempt(
        "ensure_context_gitignore",
        lambda: ensure_context_gitignore(context_dir),
        errors,
    )
    _attempt(
        "ensure_context_gitattributes",
        lambda: ensure_context_gitattributes(context_dir),
        errors,
    )
    if _attempt(
        "remove_legacy_enrich_plan",
        lambda: remove_legacy_enrich_plan(context_dir),
        errors,
    ):
        removed.append("_enrich_plan.json")
    retired = _attempt("retire_paths", lambda: retire_paths(context_dir), errors)
    if retired is not None:
        retired_removed, retired_backed_up, retired_errors = retired
        removed.extend(retired_removed)
        backed_up.extend(retired_backed_up)
        errors.extend(f"retire_paths: {error}" for error in retired_errors)
    if isinstance(package_version, str) and package_version.strip():
        dropped = _attempt(
            "scope_cache_to_version",
            lambda: scope_cache_to_version(context_dir / "cache", package_version),
            errors,
        )
        if dropped:
            removed.append(f"cache: {dropped} stale extraction entries")

    return LayoutMigration(
        removed=tuple(removed),
        backed_up=tuple(backed_up),
        errors=tuple(errors),
    )


# --- Shared report lines

_REPORT_PREFIX = "  .context/        ->  "
_REPORT_CAP = 5
_STAMP_FIX_COMMAND = "dummyindex context rebuild --changed"


def _capped_lines(
    items: tuple[str, ...],
    cap: int,
    line: Callable[[str], str],
    overflow: Callable[[int], str],
) -> list[str]:
    """The first ``cap`` items as lines, then one overflow line for the rest."""
    shown = max(cap, 0)
    lines = [line(item) for item in items[:shown]]
    hidden = len(items) - len(lines)
    if hidden > 0:
        lines.append(overflow(hidden))
    return lines


def format_migration_report(
    migration: LayoutMigration,
    failed: tuple[tuple[str, str], ...] = (),
    *,
    prefix: str = _REPORT_PREFIX,
    cap: int = _REPORT_CAP,
) -> list[str]:
    """Render a migration outcome (and refresh failures) as printable lines. Pure: no I/O.

    Shared by the install auto-init and ``context rebuild``. In order: ``removed``,
    ``backed_up`` and ``errors`` (as ``warning: migration …``), each capped at ``cap`` plus
    an ``… and N more`` line; then each ``RefreshResult.failed`` ``(artifact, error)``,
    uncapped, saying the version stamp was not advanced and how to retry. An empty
    migration with no failures renders ``[]``.
    """
    lines = _capped_lines(
        migration.removed,
        cap,
        lambda path: f"{prefix}removed {path}",
        lambda hidden: f"{prefix}… and {hidden} more removed",
    )
    lines += _capped_lines(
        migration.backed_up,
        cap,
        lambda path: f"{prefix}backed up to .context/{path}",
        lambda hidden: f"{prefix}… and {hidden} more backed up",
    )
    lines += _capped_lines(
        migration.errors,
        cap,
        lambda error: f"{prefix}warning: migration {error}",
        lambda hidden: f"{prefix}… and {hidden} more migration warnings",
    )
    lines += [
        f"{prefix}warning: {artifact} failed ({error}); version stamp not "
        f"advanced — fix the cause, then run `{_STAMP_FIX_COMMAND}`"
        for artifact, error in failed
    ]
    return lines
