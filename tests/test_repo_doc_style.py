"""Repo docs (STE C8 scope) keep zero strict style violations; advice rules never fail."""

from __future__ import annotations

import shutil
from pathlib import Path

import pytest

from dummyindex.context.domains import docbudget
from dummyindex.context.domains.docbudget.constants import STE_RULESET_VERSION
from tests.paths import REPO_ROOT

_RATCHET = REPO_ROOT / "tests" / "data" / "repo-style-budget.txt"
_SCOPE_GLOBS = (
    "docs/guide/*.md",
    "docs/reference/*.md",
    "docs/COMMANDS.md",
    "README.md",
    "dummyindex/skills/**/*.md",
)


def _scope(root: Path) -> dict[str, Path]:
    """In-scope docs under ``root``, keyed by POSIX path. New files join automatically."""
    found: dict[str, Path] = {}
    for pattern in _SCOPE_GLOBS:
        for path in root.glob(pattern):
            if path.is_file():
                found[path.relative_to(root).as_posix()] = path
    return dict(sorted(found.items()))


def _check(root: Path, ratchet: dict[str, int]) -> list[str]:
    """Problems: files over their ratchet value (unlisted files get 0), stale entries."""
    scope = _scope(root)
    problems: list[str] = []
    for rel, path in scope.items():
        count = docbudget.count_violations(path)
        limit = ratchet.get(rel, 0)
        if count <= limit:
            continue
        details = [
            f"{rel}:{v.line} [{v.rule}] {v.excerpt}"
            for v in docbudget.lint_text(path.read_text(encoding="utf-8"))
            if v.severity == "strict"
        ]
        problems.append(
            f"{rel}: {count} strict > ratchet {limit}\n  " + "\n  ".join(details)
        )
    problems.extend(
        f"stale ratchet entry (no such file): {rel}"
        for rel in ratchet
        if not (root / rel).is_file()
    )
    return problems


def _copy_scope(dest: Path) -> None:
    for rel, path in _scope(REPO_ROOT).items():
        target = dest / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, target)


@pytest.mark.unit
def test_repo_style_ratchet_has_current_ruleset_header() -> None:
    assert _RATCHET.is_file(), "tests/data/repo-style-budget.txt is missing"
    assert docbudget.read_ratchet_ruleset(_RATCHET) == STE_RULESET_VERSION


@pytest.mark.unit
def test_repo_style_ratchet_entries_are_all_zero() -> None:
    ratchet = docbudget.read_ratchet(_RATCHET)
    nonzero = {rel: n for rel, n in ratchet.items() if n != 0}
    assert not nonzero, f"repo-style-budget.txt entries must be 0 (C8): {nonzero}"


@pytest.mark.unit
def test_repo_docs_within_style_ratchet() -> None:
    problems = _check(REPO_ROOT, docbudget.read_ratchet(_RATCHET))
    assert not problems, "\n".join(problems)


@pytest.mark.unit
def test_repo_style_ratchet_has_no_stale_entries() -> None:
    ratchet = docbudget.read_ratchet(_RATCHET)
    missing = [rel for rel in ratchet if not (REPO_ROOT / rel).is_file()]
    assert not missing, f"stale repo-style-budget.txt entries: {missing}"


@pytest.mark.unit
def test_repo_style_scope_excludes_history_and_sources() -> None:
    scope = _scope(REPO_ROOT)
    for excluded in ("CHANGELOG.md", "docs/README.md", "docs/EVOLUTION.md"):
        assert excluded not in scope
    assert not [rel for rel in scope if rel.startswith("docs/sources/")]


@pytest.mark.unit
def test_advice_rules_never_fail_a_file(tmp_path: Path) -> None:
    """C1: advice (ing-form, passive) prints but never counts toward a failure."""
    text = "This report is being generated by the tool. The file was written by hand.\n"
    violations = docbudget.lint_text(text)
    assert violations, "fixture must trip an advice rule"
    assert all(v.severity == "advice" for v in violations)
    doc = tmp_path / "advice.md"
    doc.write_text(text, encoding="utf-8")
    assert docbudget.count_violations(doc) == 0


@pytest.mark.unit
def test_probe_long_sentence_in_scoped_doc_fails(tmp_path: Path) -> None:
    _copy_scope(tmp_path)
    ratchet = docbudget.read_ratchet(_RATCHET)
    assert _check(tmp_path, ratchet) == []
    long_sentence = "The " + " ".join(["word"] * 20) + "."  # 21 words
    target = tmp_path / "README.md"
    target.write_text(
        target.read_text(encoding="utf-8") + f"\n{long_sentence}\n", encoding="utf-8"
    )
    problems = _check(tmp_path, ratchet)
    assert any(
        p.startswith("README.md:") and "[long-sentence]" in p for p in problems
    ), problems


@pytest.mark.unit
def test_probe_contraction_in_scoped_doc_fails(tmp_path: Path) -> None:
    _copy_scope(tmp_path)
    ratchet = docbudget.read_ratchet(_RATCHET)
    target = tmp_path / "docs" / "COMMANDS.md"
    target.write_text(
        target.read_text(encoding="utf-8") + "\nThe index isn't ready.\n",
        encoding="utf-8",
    )
    problems = _check(tmp_path, ratchet)
    assert any(
        p.startswith("docs/COMMANDS.md:") and "[contraction]" in p for p in problems
    ), problems


@pytest.mark.unit
def test_probe_new_scoped_file_with_one_strict_violation_fails(tmp_path: Path) -> None:
    _copy_scope(tmp_path)
    ratchet = docbudget.read_ratchet(_RATCHET)
    new = tmp_path / "docs" / "guide" / "99-new-page.md"
    new.write_text("# New page\n\nThis is fine; this is not.\n", encoding="utf-8")
    problems = _check(tmp_path, ratchet)
    assert any(
        p.startswith("docs/guide/99-new-page.md: 1 strict > ratchet 0")
        and "[semicolon]" in p
        for p in problems
    ), problems
